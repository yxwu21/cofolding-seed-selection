"""Generate supplementary manuscript macros from frozen E24/E25 outputs."""
from pathlib import Path
import csv
import json

BASE = Path(__file__).resolve().parents[1]
PAPER = BASE / "paper"

def fmt(x, digits=3):
    if abs(x) < 0.5 * 10 ** -digits:
        x = 0
    return f"{x:.{digits}f}".replace("-", "$-$")

models = {"Chai": "seedext_v1", "Protenix": "seedext_v2/protenix",
          "BoltzTwo": "seedext_v2/boltz2", "BoltzOne": "seedext_v2/boltz"}
summaries = {k: json.loads((BASE / "results" / p / "summary.json").read_text()) for k, p in models.items()}
extra = {}
for word, s in summaries.items():
    extra[f"XtNExcluded{word}"] = str(s["n_systems"] - s["n_complete"])
    extra[f"XtReplScoreCorr{word}"] = fmt(s["replication"]["score_corr"])
    extra[f"XtReplQShare{word}"] = fmt(100 * s["replication"]["q_share_within_0.01"], 0)
    extra[f"XtRuleCapFiveMaxLoss{word}"] = fmt(max(r["positive_loss"] for r in s["confidence_rule"]["cap_5"].values()))
    if "min_complete" in s:
        extra[f"XtMinComplete{word}"] = str(s["min_complete"])
extra["XtNExcludedNew"] = str(sum(int(extra[f"XtNExcluded{k}"]) for k in models if k != "Chai"))
extra["XtRetDeltaHighBoltzOne"] = fmt(summaries["BoltzOne"]["delta_5_20_ret_q"]["high"][0])
extra["XtPrimaryMargin"] = fmt(summaries["BoltzOne"]["primary"]["margin"], 2)
extra["XtBootstrapReps"] = f"{summaries['BoltzOne']['bootstrap']['reps']:,}"
ks = {}
for word, path in models.items():
    rows = list(csv.DictReader((BASE / "results" / path / "kstar.csv").open()))
    ks[word] = { (r['outcome'], r['tier']): int(r['k_star']) for r in rows
                 if r['scheme'] == 'design' and float(r['threshold']) == 0.005 }
extra['XtKstarRetPool'] = str(ks['Chai']['ret_q', 'pool'])
assert all(k['ret_q', 'pool'] == int(extra['XtKstarRetPool']) for k in ks.values())
low = [k['orc_q', 'low'] for k in ks.values()]
extra['XtKstarOrcLowRange'] = f'{min(low)}--{max(low)}'
(PAPER / "generated/seedext_review_details.tex").write_text(
    "% Generated by scripts/seedext_v2_paper_details.py from frozen E24/E25 analysis outputs; do not edit.\n" +
    "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in extra.items()) + "\n")
